"""Построение модели классификации
с помощью Scikit-learn
Есть набор данных с транзакциями, в  котором указаны магазины, сумма
продажи и сумма скидки:
    # Исходные данные"""


"""
Ваша задача состоит в том, чтобы построить простую модель классификации для предсказания того, 
что транзакция относится к крупным продажам
(больше 250).

Что для этого нужно сделать?
1. Создать столбец HighSales для целевой переменной, значение которого
будет равно единице, если сумма продажи превышает $250, а  иначе
нулю.
2. Воспользоваться библиотекой Scikit-learn для построения модели случайного леса, 
предсказывающей значение целевой переменной HighSales на основе значений предикторов SalesAmount и Discount.
3. Разделить набор данных на обучающую и тестовую выборки.
4. Обучить модель, предсказать исходы на тестовой выборке и вывести
результаты.
Решение"""

from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
import pandas as pd
import numpy as np

data = {'TransactionID': [101, 102, 103, 104, 105],
'SalesAmount': [250, np.nan, 340, 400, 200],
'Discount': [10, 15, 20, np.nan, 5],
'Store': ['A', 'B', 'A', 'C', 'B']}
df = pd.DataFrame(data)

# Шаг 1: Обрабатываем пропущенные значения
df['SalesAmount'] = df['SalesAmount'].fillna(df['SalesAmount'].mean())
df['Discount'] = df['Discount'].fillna(df['Discount'].mean())
"""Модель машинного обучения не умеет работать с пропусками (NaN). Если оставить пропуски, модель выдаст ошибку.
Поэтому пропуски нужно чем-то заменить. Самый простой способ — заменить на среднее."""
# Шаг 2: Создаем столбец с именем HighSales
df['HighSales'] = (df['SalesAmount'] > 250).astype(int)
# Шаг 3: Определяем признаки и целевую переменную
X = df[['SalesAmount', 'Discount']]
y = df['HighSales']
# Шаг 4: Разделяем данные на обучающую и тестовую выборки
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)
# Шаг 5: Обучаем модель случайного леса
clf = RandomForestClassifier(random_state=42)
clf.fit(X_train, y_train)
# Шаг 6: Предсказываем исходы на тестовой выборке и выводим результаты
y_pred = clf.predict(X_test)
print("Предсказания:", y_pred)


# Создаём копию тестовых данных с результатами
results = X_test.copy()
results['Actual_HighSales'] = y_test.values  # истинные значения
results['Predicted_HighSales'] = y_pred       # предсказанные значения
results['TransactionID'] = df.loc[X_test.index, 'TransactionID']  # ID транзакции

print("Результаты классификации:")
print(results)

"""Это значит, что модель предсказала две транзакции:

    Транзакция	Предсказание	Что это означает
    1-я	1	Модель думает: это крупная продажа (>250)
    2-я	0	Модель думает: это НЕ крупная продажа (≤250)

Почему предсказаний всего два?
Потому что вы разделили данные на обучающую и тестовую выборки с параметром test_size=0.3.

У вас было 5 транзакций.
test_size=0.3 означает, что 30% данных ушло на тестирование.
30% от 5 = 1.5 → округляется до 2 транзакций.
"""