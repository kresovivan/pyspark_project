"""Есть простой набор данных с суммами продаж:

Что делает этот скрипт (коротко)
Скрипт превращает продажи [100, 200, 50, 400, 300] в z-оценки, которые показывают: 
насколько далеко каждый магазин от среднего, измеренное в "средних отклонениях".
Результат: [-0.97, 0.15, -1.46, 1.83, 0.44]
Отрицательные числа → продажи ниже среднего
Положительные → выше среднего
Чем дальше от нуля, тем сильнее отклонение


z-оценка — это число, которое показывает насколько далеко значение находится от среднего, 
измеренное в «средних отклонениях».
Стандартное отклонение — это число, которое показывает, насколько сильно данные разбросаны вокруг среднего значения.





Зачем это нужно? Реальные бизнес-задачи
1. Сравнение несравнимого (разные шкалы)
Задача: У вас есть магазины. У каждого свои продажи, количество сотрудников, площадь, трафик покупателей. Как понять, что важнее?

Магазин	Продажи (тыс. руб)	Количество сотрудников
A	100	5
B	200	20
C	50	3
D	400	25
E	300	15
В абсолютных цифрах продажи от 50 до 400, а сотрудники — от 3 до 25. Непонятно, что сильнее влияет на успех.


Решение: Стандартизируем оба показателя:

    Магазин	z-оценка продаж	        z-оценка сотрудников	Вывод
    A	          -0.97	                 -0.55	            Оба показателя ниже среднего
    B	           0.15	                  0.67	            Сотрудников много, продажи чуть выше среднего → низкая эффективность
    C	          -1.46                  -0.90	            Всё плохо
    D	           1.83	                  1.19	            Продажи растут быстрее, чем сотрудники → высокая эффективность
    E	           0.44	                 -0.40	            Мало сотрудников, продажи выше среднего → супер-эффективность!
    Бизнес-решение: Изучить опыт магазина E (как при малом количестве сотрудников делать хорошие продажи) 
    и разобраться с магазином B (много сотрудников, а продажи невысокие).
    
2. Поиск аномалий (выбросов)
Задача: Найти магазины, которые работают аномально хорошо или плохо, чтобы принять меры.
По правилу трёх сигм: Если z-оценка по модулю больше 3 — это аномалия (очень редко).
В вашем примере:
z-оценка = 1.83 (магазин D) — не аномалия, просто хороший магазин
z-оценка = -1.46 (магазин C) — не аномалия, просто плохой магазин

Но если бы z-оценка была 3.5 или -3.2 — это сигнал "что-то не так". Либо магазин-рекордсмен 
(проверить, нет ли ошибки в данных), либо магазин-банкрот.

«Стандартизация нужна, чтобы привести все показатели к единой шкале. Это позволяет сравнивать 
несравнимое (например, продажи и количество сотрудников), искать аномалии и обучать модели машинного обучения, 
которые иначе переобучатся на большие числа.»

"""
# Исходные данные
sales = [100, 200, 50, 400, 300]
"""Ваша задача состоит в том, чтобы стандартизировать эти данные, вычислив 
для каждого значения z-оценку с применением только библиотеки NumPy.
Решение"""
import numpy as np
# Шаг 1: Рассчитываем среднее и стандартное отклонение
mean_sales = np.mean(sales) # (x₁ + x₂ + ... + xn) / n
std_sales = np.std(sales) # √( (∑(x-mean)²) / n )
# Шаг 2: Вычисляем z-оценки
z_scores = (sales - mean_sales) / std_sales
print(z_scores)
