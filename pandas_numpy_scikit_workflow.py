"""Объединение библиотек Pandas, NumPy 
и Scikit-learn в одном рабочем процессе
Есть набор данных с транзакциями, в  котором указаны магазины, сумма 
продажи и сумма скидки:
Ваша задача состоит в том, чтобы:
1) обработать пропущенные значения в столбцах SalesAmount и Discount, 
заменив их на средние значения;
2) применить логарифмическое преобразование к  столбцу SalesAmount
с помощью библиотеки NumPy;
3) построить модель классификации с помощью библиотеки Scikit-learn 
для предсказания того, что транзакция относится к крупным продажам 
(HighSales);
4) разделить набор данных на обучающую и тестовую выборки;
5) обучить модель, предсказать исходы на тестовой выборке и вывести 
результаты.
Решение"""


# ============================================================================
# БЛОК 1: ИМПОРТ БИБЛИОТЕК
# ============================================================================

# Импортируем функцию для разделения данных на обучающую и тестовую выборки
# train_test_split: перемешивает и делит данные (обычно 70-80% на обучение, остальное на тест)
from sklearn.model_selection import train_test_split

# Импортируем классификатор "Случайный лес"
# RandomForestClassifier: модель, которая создаёт множество решающих деревьев
# и усредняет их ответы (ансамблевый метод)
from sklearn.ensemble import RandomForestClassifier

# Импортируем Pandas (для работы с таблицами)
# pandas позволяет создавать DataFrame - удобные таблицы с колонками и индексами
import pandas as pd

# Импортируем NumPy (для работы с числами и массивами)
# NumPy умеет считать среднее, стандартное отклонение, логарифмы и т.д.
import numpy as np

# ============================================================================
# БЛОК 2: СОЗДАНИЕ ИСХОДНЫХ ДАННЫХ
# ============================================================================

# Создаём словарь с данными о транзакциях
# Ключи словаря = названия будущих колонок
# Значения = списки значений для каждой строки
data = {'TransactionID': [101, 102, 103, 104, 105],  # ID транзакций (уникальные номера)
'SalesAmount': [250, np.nan, 340, 400, 200],  # Сумма продажи (np.nan = пропущенное значение)
'Discount': [10, 15, 20, np.nan, 5],         # Скидка в рублях или процентах
'Store': ['A', 'B', 'A', 'C', 'B']}          # Буквенное обозначение магазина

# Превращаем словарь в DataFrame (таблицу) из библиотеки Pandas
# df = data frame (таблица с колонками и строками)
df = pd.DataFrame(data)

# ============================================================================
# БЛОК 3: ОБРАБОТКА ПРОПУЩЕННЫХ ЗНАЧЕНИЙ (ЗАПОЛНЕНИЕ ПРОПУСКОВ)
# ============================================================================

# Шаг 1: Заполняем пропуски в колонке 'SalesAmount'
# df['SalesAmount'] - берём колонку с суммами продаж
# .mean() - считаем среднее арифметическое (игнорируя пропуски)
# .fillna(...) - заменяет все пропуски (NaN) на среднее значение
# Результат сохраняем обратно в колонку 'SalesAmount'
df['SalesAmount'] = df['SalesAmount'].fillna(df['SalesAmount'].mean())

# Шаг 2: Заполняем пропуски в колонке 'Discount' (делаем то же самое)
df['Discount'] = df['Discount'].fillna(df['Discount'].mean())

# ============================================================================
# БЛОК 4: ЛОГАРИФМИЧЕСКОЕ ПРЕОБРАЗОВАНИЕ (ДОБАВЛЯЕМ НОВЫЙ ПРИЗНАК)
# ============================================================================

# np.log() - натуральный логарифм (основание e ≈ 2.718)
# Логарифм помогает "сжать" большие числа и лучше показывать процентные изменения
# Создаём новую колонку 'LogSales' (логарифм от суммы продажи)
df['LogSales'] = np.log(df['SalesAmount'])

# ============================================================================
# БЛОК 5: СОЗДАНИЕ ЦЕЛЕВОЙ ПЕРЕМЕННОЙ (ТО, ЧТО МОДЕЛЬ БУДЕТ ПРЕДСКАЗЫВАТЬ)
# ============================================================================

# Создаём колонку 'HighSales' (крупная продажа?)
# (df['SalesAmount'] > 250) - проверяем: сумма продажи больше 250?
# Результат проверки: True (если больше) или False (если не больше)
# .astype(int) - превращает True → 1, False → 0
# Теперь: 1 = крупная продажа, 0 = не крупная
df['HighSales'] = (df['SalesAmount'] > 250).astype(int)

# ============================================================================
# БЛОК 6: ОПРЕДЕЛЯЕМ ПРИЗНАКИ (X) И ЦЕЛЕВУЮ ПЕРЕМЕННУЮ (y)
# ============================================================================

# X - матрица признаков (входные данные, на основе которых модель будет учиться)
# Берём колонки: 'SalesAmount' (сумма продажи),
#                'Discount' (скидка),
#                'LogSales' (логарифм суммы продажи)
X = df[['SalesAmount', 'Discount', 'LogSales']]

# y - целевая переменная (то, что модель должна предсказать)
# Берём колонку 'HighSales' (1 - крупная продажа, 0 - не крупная)
y = df['HighSales']

# ============================================================================
# БЛОК 7: РАЗДЕЛЕНИЕ ДАННЫХ НА ОБУЧАЮЩУЮ И ТЕСТОВУЮ ВЫБОРКИ
# ============================================================================

# train_test_split - разделяет данные на две части:
#   - train (обучающая): на ней модель учится (70%)
#   - test (тестовая): на ней модель проверяется (30%)
# test_size=0.3 - означает, что 30% данных уйдёт на тест, 70% на обучение
# random_state=42 - фиксирует случайность (при любом запуске разделение будет одинаковым)
#                   42 - просто популярное число (как "якорь" случайности)
X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.3, random_state=42)

# Что получилось:
# X_train - признаки для обучения (3 признака × 3 строки)
# X_test  - признаки для теста    (3 признака × 2 строки)
# y_train - ответы для обучения   (3 ответа)
# y_test  - ответы для теста      (2 ответа)

# ============================================================================
# БЛОК 8: СОЗДАНИЕ И ОБУЧЕНИЕ МОДЕЛИ СЛУЧАЙНОГО ЛЕСА
# ============================================================================

# RandomForestClassifier() - создаём объект модели (классификатор на основе случайного леса)
# random_state=42 - фиксируем случайность (чтобы модель всегда выдавала одинаковый результат)
clf = RandomForestClassifier(random_state=42)

# clf.fit() - обучаем модель (подбираем параметры)
# X_train - входные данные для обучения (признаки)
# y_train - правильные ответы для обучения (целевая переменная)
# Модель ищет закономерности вида:
# "Если SalesAmount > 300 и Discount < 10 → то HighSales = 1" и т.д.
clf.fit(X_train, y_train)

# ============================================================================
# БЛОК 9: ПРЕДСКАЗАНИЕ НА ТЕСТОВОЙ ВЫБОРКЕ И ВЫВОД РЕЗУЛЬТАТОВ
# ============================================================================

# clf.predict() - делает предсказание на основе тестовых данных
# X_test - передаём признаки тестовой выборки
# Модель возвращает массив предсказаний (1 или 0 для каждой тестовой строки)
y_pred = clf.predict(X_test)

# Выводим предсказания на экран
print("Предсказания:", y_pred)

# ============================================================================
# КОММЕНТАРИЙ К РЕЗУЛЬТАТУ:
# Предсказания: [1 0]
#
# Это означает:
# - Первая тестовая транзакция (индекс 2): предсказано 1 (крупная продажа)
# - Вторая тестовая транзакция (индекс 4): предсказано 0 (не крупная продажа)
# ============================================================================