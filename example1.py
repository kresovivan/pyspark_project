# Импорт необходимых библиотек
import pandas as pd  # Для работы с таблицами и анализа данных
import numpy as np   # Для математических операций (np.nan для пропусков)
import matplotlib.pyplot as plt  # Для построения графиков

# Простые данные: ежедневные продажи в розничных магазинах
# Создаем словарь с данными
data = {
    # Генерируем 30 дат с 1 января 2023 года с интервалом в 1 день
    'Date': pd.date_range(start='2023-01-01', periods=30, freq='D'),
    
    # Список продаж (np.nan - пропущенные значения)
    'Sales': [200, 220, np.nan, 250, 260, 240, np.nan, 300, 280, 290,
              310, 305, 315, np.nan, 330, 340, 335, 345, 350, 360,
              355, np.nan, 370, 375, 380, 385, 390, 395, 400, 410],
    
    # Список категорий товаров (A, B, C)
    'Category': ['A', 'B', 'A', 'C', 'B', 'A', 'C', 'B', 'A', 'C',
                 'A', 'B', 'C', 'A', 'B', 'C', 'A', 'B', 'C', 'A',
                 'B', 'C', 'A', 'B', 'C', 'A', 'B', 'C', 'A', 'B']
}

# Преобразуем словарь в DataFrame pandas 
# DataFrame - это табличная структура данных
df = pd.DataFrame(data)

# Выводим первые несколько строк датафрейма
print("Исходный датафрейм:")
print(df.head())  # head() показывает первые 5 строк

# Базовая статистика по столбцу Sales
print("\nБазовая статистика по столбцу Sales:")
print(df['Sales'].describe())  # describe() показывает: count, mean, std, min, max, квартили

# ИСПРАВЛЕННАЯ СТРОКА:
# Обработка пропущенных значений
# В новых версиях pandas fillna() не принимает параметр 'method'
# Используем ffill() (forward fill) - заполняет пропуски предыдущим значением
df['Sales_Filled'] = df['Sales'].ffill()  # <-- ИСПРАВЛЕНИЕ ЗДЕСЬ

# Расчет скользящего среднего
# rolling(window=7) - создает окно из 7 дней
# mean() - вычисляет среднее арифметическое в этом окне
# Скользящее среднее сглаживает колебания и показывает тренд
df['Rolling_Avg_7d'] = df['Sales_Filled'].rolling(window=7).mean()

# Группировка по столбцу Category с вычислением средних продаж
# groupby('Category') - группирует строки по категориям (A, B, C)
# ['Sales_Filled'] - берем столбец с заполненными продажами
# mean() - вычисляем среднее значение для каждой группы
category_avg = df.groupby('Category')['Sales_Filled'].mean()
print("\nСредние продажи по категориям:")
print(category_avg)

# Оптимизация типов данных
# to_numeric() - преобразует данные в числовой тип
# downcast='float' - уменьшает размер чисел (экономит память)
# Например: float64 (8 байт) → float32 (4 байта)
df['Sales'] = pd.to_numeric(df['Sales'], downcast='float')
df['Sales_Filled'] = pd.to_numeric(df['Sales_Filled'], downcast='float')
df['Rolling_Avg_7d'] = pd.to_numeric(df['Rolling_Avg_7d'], downcast='float')

# Выводим информацию об использовании памяти
print("\nИспользование памяти после оптимизации:")
print(df.memory_usage(deep=True))  # memory_usage() показывает объем памяти в байтах

# Визуализация данных
# Создаем график размером 12x6 дюймов
plt.figure(figsize=(12, 6))

# Строим первый график: заполненные продажи (сплошная линия)
plt.plot(df['Date'], df['Sales_Filled'], label='Продажи (заполненные)', linewidth=2)

# Строим второй график: 7-дневное скользящее среднее (пунктирная линия)
plt.plot(df['Date'], df['Rolling_Avg_7d'], label='7-дневное скользящее среднее', 
         linestyle='--', linewidth=2)

# Добавляем заголовок графика
plt.title('Ежедневные продажи и семидневные скользящие средние', fontsize=14)

# Подписываем оси координат
plt.xlabel('Дата', fontsize=12)
plt.ylabel('Продажи', fontsize=12)

# Добавляем легенду (обозначения линий)
plt.legend()

# Добавляем сетку для удобства чтения
plt.grid(True, alpha=0.3)  # alpha=0.3 делает сетку полупрозрачной

# Поворачиваем подписи дат на 45 градусов для лучшей читаемости
plt.xticks(rotation=45)

# Автоматически подгоняем элементы графика
plt.tight_layout()

# Отображаем график на экране
plt.show()