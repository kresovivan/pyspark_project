"""Есть простой набор данных с суммами продаж:
# Исходные данные
sales = [100, 200, 50, 400, 300]
Ваша задача состоит в том, чтобы:
1) при помощи библиотеки NumPy применить операцию логарифмического преобразования к этим данным;
2) вывести результат преобразования.


Задача, которую решает этот скрипт (реальный бизнес-кейс)
Представьте, что вы аналитик в Cargill. У вас есть 5 магазинов с разными продажами:

Магазин	Продажи (тыс. руб)
A	100
B	200
C	50
D	400
E	300
Вас просят найти магазины, которые продают «аномально много» или «аномально мало», чтобы:
Аномально много → откорректировать план продаж
Аномально мало → проверить, почему так плохо

Проблема: обычные числа не подходят для сравнения
Если посмотреть на обычные продажи [100, 200, 50, 400, 300], то:

Магазин D (400) кажется огромным
Магазин C (50) кажется крошечным
Но так ли это на самом деле?



Решение: логарифм показывает «во сколько раз», а не «на сколько»
Считаем среднее арифметическое обычных продаж:
(100 + 200 + 50 + 400 + 300) / 5 = 210

Теперь смотрим отклонения от среднего:
Магазин	  Продажи	Отклонение от среднего	Вывод
D	         400	      +190	              Кажется, очень много
C	          50	      -160	              Кажется, очень мало
Но давайте посмотрим во сколько раз:

Магазин D: 400 / 210 = в 1.9 раза выше среднего
Магазин C: 210 / 50 = в 4.2 раза ниже среднего
По факту магазин C аномальнее (в 4.2 раза отстаёт), чем магазин D лидирует (всего в 1.9 раза).



Как логарифм это автоматически показывает
Логарифмы пересчитывают продажи так, чтобы разница в логарифмах = разница в разах:

Магазин	Продажи	    log(продажи)	Отклонение от среднего log	    Вывод
A	         100	4.61	                   -0.23	           Чуть ниже
B	         200	5.30	                   +0.46	           Выше
C	         50	    3.91	                   -0.93	           Сильно ниже (аномалия!)
D	         400	5.99	                   +0.75	           Выше
E	         300	5.70	                   +0.46	           Выше
Среднее логарифмов: (4.61+5.30+3.91+5.99+5.70)/5 = 5.10

Теперь видно:
Магазин C (log=3.91) отклоняется на -0.93 — это самая большая аномалия
Магазин D (log=5.99) отклоняется на +0.75 — аномалия, но меньше
Вывод: Магазин C требует внимания в первую очередь (проблема), а не магазин D

А если вы спросите: «Но ведь можно просто поделить одно на другое?»
Да, можно. Но когда у вас миллионы строк продаж по десяткам магазинов, вы не будете вручную делить. 
Логарифмическое преобразование позволяет автоматически в одной формуле сделать так, 
чтобы модель или аналитик видели пропорции, а не абсолют.

Именно для этого и нужен np.log(sales).


Решение"""
import numpy as np
sales = [100, 200, 50, 400, 300]
# Шаг 1: Применяем операцию логарифмического преобразования
log_sales = np.log(sales)
print(log_sales)